//! FDT `/reserved-memory` 固件保留区解析测试。

#![no_std]
#![no_main]
#![feature(alloc_error_handler)]

extern crate alloc;

test_harness::test_main!(
    simplekernel::boot::InitLevel::Memory,
    test_firmware_reserved_memory
);

/// `KernelFdt` 应能从 `/reserved-memory/firmware@...` 解析固件保留区。
fn test_firmware_reserved_memory() {
    let fdt = simplekernel::fdt::KernelFdt::new(FIRMWARE_RESERVED_DTB.as_ptr() as usize)
        .expect("测试 DTB 应可解析");

    let (addr, size) = fdt
        .firmware_reserved_memory()
        .expect("应能解析固件 reserved-memory 节点");

    assert_eq!(addr, 0x8000_0000);
    assert_eq!(size, 0x0020_0000);
}

